"""
Shared Pydantic Schemas for System & Architecture Evaluation.
"""

from typing import Dict, Any, Optional
from pydantic import BaseModel, Field


class EvaluationMetrics(BaseModel):
    task_success: float = Field(..., ge=0.0, le=1.0, description="Overall task completion score (0.0 - 1.0)")
    quality: float = Field(..., ge=0.0, le=1.0, description="Output quality rating (0.0 - 1.0)")
    completeness: float = Field(..., ge=0.0, le=1.0, description="Completeness of subtasks fulfilled (0.0 - 1.0)")
    execution_time_seconds: float = Field(..., ge=0.0, description="Total execution duration in seconds")
    agent_count: int = Field(..., ge=1, description="Number of active agents in the architecture")
    tool_call_count: int = Field(default=0, ge=0, description="Total tool invocations during execution")


class EvaluationResult(BaseModel):
    evaluation_id: str = Field(..., description="Unique evaluation identifier")
    task_id: str = Field(..., description="ID of evaluated task")
    architecture_id: str = Field(..., description="ID of evaluated architecture")
    metrics: EvaluationMetrics = Field(..., description="Quantitative metric payload")
    feedback_summary: str = Field(..., description="Textual evaluation summary of strengths and deficiencies")
    raw_output: Optional[str] = Field(default=None, description="Final output generated by the dynamic agent team")

    class Config:
        json_schema_extra = {
            "example": {
                "evaluation_id": "eval_001",
                "task_id": "task_001",
                "architecture_id": "arch_001",
                "metrics": {
                    "task_success": 0.72,
                    "quality": 0.68,
                    "completeness": 0.75,
                    "execution_time_seconds": 14.5,
                    "agent_count": 3,
                    "tool_call_count": 4
                },
                "feedback_summary": "The generated report lacks independent factual verification."
            }
        }
